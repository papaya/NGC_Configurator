import { validateProject } from "./validate.js";
import { planNgcEvents } from "./ngc-events.js";

function quoteValue(value) {
  return String(value).replaceAll("\\", "\\\\").replaceAll('"', '\\"').replace(/[\r\n]+/g, " ");
}

function labelId(control, bank) {
  return `mb_${control.id.replace(/[^a-zA-Z0-9_]/g, "_")}_b${bank.order}`;
}

function formatEvent(event) {
  const { directive, control, assignment, bank, eventId } = event;
  const eventType = assignment.eventType || "CC";
  const fields = [`id=${eventId}`, `hw_id=${control.hwId}`, `type=${eventType}`];
  if (eventType === "Meta") {
    if (control.kind === "button") fields.push(`button_mode=${assignment.buttonMode || "OnOnly"}`);
    fields.push(`meta=${assignment.meta}`);
  } else {
    const messageType = assignment.messageType ?? "CC";
    fields[2] = `type=${messageType}`;
    fields.push(`chn=${assignment.channel}`);
    fields.push(messageType === "NoteOn" ? `key=${assignment.key ?? 60}` : `cc=${assignment.cc}`);
    fields.push(`range=${assignment.valueMin}:${assignment.valueMax}`);
    if (assignment.bankScoped !== false) fields.push(`bank=${bank.order}`);
    if (assignment.led?.forwardId != null) fields.push(`fwd_id=RGBLED:${assignment.led.forwardId}`);
    if (assignment.led?.pattern != null) fields.push(`rgbled_pattern=${assignment.led.pattern}`);
    if (Array.isArray(assignment.led?.eventHsv)) fields.push(`hsv=${assignment.led.eventHsv.join(":")}`);
    if (control.kind === "button") fields.push(`button_mode=${assignment.buttonMode || "Toggle"}`);
  }
  fields.push(`label="^${labelId(control, bank)}"`);
  return `${directive}\t${fields.join("\t")}`;
}

function generateNgr(project) {
  const sections = [];
  for (const bank of [...project.banks].sort((a, b) => a.order - b.order)) {
    const hsvByTarget = new Map();
    for (const control of project.controls) {
      const led = project.assignments?.[bank.id]?.[control.id]?.led;
      if (!led?.hsv || led.scriptTargetId == null) continue;
      hsvByTarget.set(led.scriptTargetId, led.hsv);
    }
    if (!hsvByTarget.size) continue;
    sections.push(`if ^section == ${bank.order}`);
    for (const [target, hsv] of hsvByTarget) sections.push(`  set_hsv RGBLED:${target} ${hsv.join(":")}`);
    sections.push(`  set ^bank ${bank.order}`, "  exit", "endif", "");
  }
  return sections.join("\n").trimEnd();
}

export function generateFiles(project, catalog) {
  const issues = validateProject(project, catalog);
  const blockers = issues.filter(issue => issue.severity === "error");
  if (blockers.length) return { files: {}, issues };

  const lines = [
    `# ${project.metadata.name}`,
    "# Generated by ModulBox NGC Configurator; hardware wiring must be checked separately.",
    "RESET_HW"
  ];
  for (const led of project.ledEvents ?? []) {
    lines.push(`EVENT_RGBLED\tid=${led.id}\tdimmed=${led.dimmed}\trange=${led.rangeMin}:${led.rangeMax}`);
  }
  for (const control of project.controls) {
    if (control.kind !== "encoder" || !control.encoderConfig) continue;
    const config = control.encoderConfig;
    lines.push(`ENC\tn=${config.n}\tsr=${config.sr}\tpins=${config.pins}\ttype=${config.type}`);
  }

  const orderedBanks = [...project.banks].sort((a, b) => a.order - b.order);
  const plannedEvents = planNgcEvents(project);
  const globalEvents = plannedEvents.filter(event => event.assignment.bankScoped === false);
  const bankLines = globalEvents.map(formatEvent);
  for (const bank of orderedBanks) {
    const bankEvents = plannedEvents.filter(event => event.assignment.bankScoped !== false && event.bank.id === bank.id);
    if (bankEvents.length) bankLines.push(`#BANK\t${bank.order}`, ...bankEvents.map(formatEvent), "");
  }
  const advancedNgc = project.advanced.ngc;
  const manualNgc = advancedNgc.length ? `\n\n# Preserved advanced NGC directives\n${advancedNgc}${advancedNgc.endsWith("\n") ? "" : "\n"}` : "";
  const structuredNgc = bankLines.length ? `\n${bankLines.join("\n").trimEnd()}` : "";
  const ngc = `${lines.join("\n")}${manualNgc}${structuredNgc}\n`;
  const advancedNgl = project.advanced.ngl;
  const labels = plannedEvents.map(({ control, assignment, bank }) => {
    const name = assignment.label || control.name;
    return `LABEL ${labelId(control, bank)} "@(1:1:1)${quoteValue(name)}"`;
  });
  const nglParts = [advancedNgl.trimEnd(), labels.length ? `# Labels generated by the project model\n${labels.join("\n")}` : ""].filter(Boolean);
  const ngl = `${nglParts.join("\n\n")}\n`;
  const baseName = safeName(project.metadata.name);
  const files = { [`${baseName}.NGC`]: ngc, [`${baseName}.NGL`]: ngl };
  const structuredNgr = generateNgr(project);
  const advancedNgr = project.advanced.ngr;
  if (advancedNgr.trim() || structuredNgr) {
    const ngrParts = [advancedNgr.trimEnd(), structuredNgr].filter(Boolean);
    files[`${baseName}.NGR`] = `${ngrParts.join("\n\n")}\n`;
  }
  return { files, issues };
}

function safeName(name) {
  const normalized = name.normalize("NFKD").replace(/\p{Diacritic}/gu, "").trim().replace(/[^a-zA-Z0-9_-]+/g, "_").replace(/^_+|_+$/g, "");
  return normalized || "ModulBox";
}
